def get_stage(stage_id: str) -> Stage | None:
    for stage in STAGES:
        if stage.id == stage_id:
            return stage
    return None


def all_criteria() -> list[tuple[Stage, Criterion]]:
    return [(stage, c) for stage in STAGES for c in stage.criteria]
